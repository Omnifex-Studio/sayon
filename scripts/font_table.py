"""Generates the runtime's built-in font, which `standard/graphics` draws
text with.

    python scripts/font_table.py <directory of font8x8's headers>

The font is font8x8 by Daniel Hepper (https://github.com/dhepper/font8x8),
after Marcel Sondaar's, from IBM's VGA fonts; all are in the public domain.
Each character is 8 by 8 pixels, a byte for each row whose lowest bit is the
row's first pixel. The table takes basic Latin, the Latin-1 supplement,
Greek, box drawing, and block elements from font8x8_basic.h,
font8x8_ext_latin.h, font8x8_greek.h, font8x8_box.h, and font8x8_block.h,
and writes crates/runtime/src/font_table.rs.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "crates" / "runtime" / "src" / "font_table.rs"
HEADERS = [
    "font8x8_basic.h",
    "font8x8_ext_latin.h",
    "font8x8_greek.h",
    "font8x8_box.h",
    "font8x8_block.h",
]
ROW = re.compile(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){7}0x[0-9A-Fa-f]{2})\s*\}\s*,?\s*//\s*U\+([0-9A-Fa-f]{4})")


def glyphs(directory):
    found = {}
    for name in HEADERS:
        for line in (directory / name).read_text(encoding="utf-8").splitlines():
            match = ROW.search(line)
            if match:
                rows = [int(part, 16) for part in match.group(1).split(",")]
                code = int(match.group(2), 16)
                # Control characters have no picture.
                if any(rows) and code >= 0x20 and not 0x7F <= code < 0xA0:
                    found[code] = rows
    return found


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: python scripts/font_table.py <directory of font8x8's headers>")
    found = glyphs(Path(sys.argv[1]))
    lines = [
        "// Generated by scripts/font_table.py from font8x8, in the public domain.",
        "// Do not edit by hand.",
        "",
        "/// The characters of the built-in font, by code point, each 8 rows of",
        "/// 8 pixels whose lowest bit is the first.",
        f"pub static GLYPHS: [(u32, [u8; 8]); {len(found)}] = [",
    ]
    for code in sorted(found):
        rows = ", ".join(f"0x{row:02X}" for row in found[code])
        lines.append(f"    (0x{code:04X}, [{rows}]),")
    lines.append("];")
    TABLE.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"wrote {len(found)} characters to {TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
