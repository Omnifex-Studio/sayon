"""Generates the runtime's Unicode tables and their test cases.

    python scripts/unicode_tables.py

Writes crates/runtime/src/unicode_tables.rs, with the properties extended
grapheme clusters are found by (Unicode Standard Annex #29), and
crates/runtime/tests/graphemes.txt, test cases whose expected clusters come
from an independent implementation of the same rules. Both use the
third-party `regex` package (pip install regex==2026.9.10), which carries
the Unicode Character Database; the version it implements is recorded in
the table, and changing it is a deliberate toolchain update.
"""

import random
import re
from pathlib import Path

import regex

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "crates" / "runtime" / "src" / "unicode_tables.rs"
CASES = ROOT / "crates" / "runtime" / "tests" / "graphemes.txt"

# Grapheme_Cluster_Break values, numbered as in the runtime; 0 is Other.
BREAKS = [
    "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
    "SpacingMark", "L", "V", "T", "LV", "LVT",
]
# Indic_Conjunct_Break values; 0 is None.
CONJUNCTS = ["Linker", "Consonant", "Extend"]

EXTENDED_PICTOGRAPHIC = 1 << 4
CONJUNCT_SHIFT = 5


def unicode_version():
    for path in Path(regex.__file__).resolve().parent.parent.glob("regex-*.dist-info/METADATA"):
        found = re.search(r"supports Unicode (\d+\.\d+\.\d+)", path.read_text(encoding="utf-8"))
        if found:
            return found.group(1)
    raise SystemExit("cannot tell which Unicode version the regex package implements")


def code_points():
    """Every code point but the surrogates, as one string."""
    return "".join(chr(cp) for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF)


def to_code_point(offset):
    return offset if offset < 0xD800 else offset + 0x800


def properties():
    text = code_points()
    values = bytearray(0x110000)
    for number, name in enumerate(BREAKS, start=1):
        for match in regex.finditer(r"\p{Grapheme_Cluster_Break=" + name + r"}+", text):
            for offset in range(match.start(), match.end()):
                values[to_code_point(offset)] |= number
    for match in regex.finditer(r"\p{Extended_Pictographic}+", text):
        for offset in range(match.start(), match.end()):
            values[to_code_point(offset)] |= EXTENDED_PICTOGRAPHIC
    for number, name in enumerate(CONJUNCTS, start=1):
        for match in regex.finditer(r"\p{Indic_Conjunct_Break=" + name + r"}+", text):
            for offset in range(match.start(), match.end()):
                values[to_code_point(offset)] |= number << CONJUNCT_SHIFT
    return values


def runs(values):
    """(first, last, value) for each run of equal values other than 0."""
    found = []
    start = 0
    for cp in range(1, 0x110001):
        if cp == 0x110000 or values[cp] != values[start]:
            if values[start]:
                found.append((start, cp - 1, values[start]))
            start = cp
    return found


def write_table(version, found):
    lines = [
        "//! Generated by scripts/unicode_tables.py from Unicode " + version + "; do not edit.",
        "",
        "/// The Unicode version the tables come from.",
        'pub const UNICODE_VERSION: &str = "' + version + '";',
        "",
        "/// `(first, last, properties)` for each run of code points whose grapheme",
        "/// properties are not the defaults, in order. The low four bits are the",
        "/// Grapheme_Cluster_Break value (see `graphemes::Break`), bit 4 is",
        "/// Extended_Pictographic, and bits 5 and 6 are Indic_Conjunct_Break",
        "/// (1 Linker, 2 Consonant, 3 Extend).",
        "#[rustfmt::skip]",
        "pub static GRAPHEME_PROPERTIES: &[(u32, u32, u8)] = &[",
    ]
    row = []
    for first, last, value in found:
        row.append("(0x%X, 0x%X, %d)," % (first, last, value))
        if len(row) == 4:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def samples(values):
    """Up to three code points for each combination of properties, so that
    every rule meets every kind of character."""
    chosen = {}
    rng = random.Random(17)
    by_value = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        by_value.setdefault(values[cp], []).append(cp)
    for value, members in sorted(by_value.items()):
        picks = [members[0], members[-1]] + rng.sample(members, min(1, len(members)))
        chosen[value] = sorted(set(picks))
    return [cp for picks in chosen.values() for cp in picks]


def clusters(text):
    return regex.findall(r"\X", text)


def case_line(text):
    parts = []
    for cluster in clusters(text):
        parts.append(" ".join("%04X" % ord(ch) for ch in cluster))
    return " | ".join(parts)


def write_cases(values):
    pool = samples(values)
    rng = random.Random(29)
    texts = []
    for a in pool:
        for b in pool:
            texts.append(chr(a) + chr(b))
    for _ in range(4000):
        texts.append("".join(chr(rng.choice(pool)) for _ in range(rng.randint(3, 8))))
    # Sequences the rules exist for.
    texts += [
        "\r\n", "é̂", "\U0001F468‍\U0001F469‍\U0001F467",
        "\U0001F44D\U0001F3FD", "\U0001F1EB\U0001F1F7\U0001F1E9\U0001F1EA\U0001F1EB",
        "क्ष", "क्‍ष", "क़्क",
        "각", "각", "؀١", "a‍\U0001F600",
    ]
    lines = [
        "# Generated by scripts/unicode_tables.py; do not edit.",
        "# Each line is a text, as hexadecimal code points; `|` separates its",
        "# extended grapheme clusters.",
    ]
    seen = set()
    for text in texts:
        if text not in seen:
            seen.add(text)
            lines.append(case_line(text))
    CASES.parent.mkdir(parents=True, exist_ok=True)
    CASES.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main():
    version = unicode_version()
    values = properties()
    found = runs(values)
    write_table(version, found)
    write_cases(values)
    print("Unicode %s: %d property runs" % (version, len(found)))


if __name__ == "__main__":
    main()
